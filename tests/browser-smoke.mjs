import { createRequire } from 'node:module';
const {chromium}=createRequire(import.meta.url)(process.env.CAREER_PLAYWRIGHT_MODULE || 'playwright');
import {mkdir,writeFile} from 'node:fs/promises';
await mkdir('outputs',{recursive:true});
const browser=await chromium.launch({headless:true,channel:process.env.CAREER_BROWSER_CHANNEL || undefined});
const page=await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'reduce'});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
await page.screenshot({path:'outputs/home-desktop.png',fullPage:true});
await page.goto('http://127.0.0.1:5173/demo',{waitUntil:'networkidle'});
await page.screenshot({path:'outputs/dashboard-desktop.png',fullPage:true});
await page.getByRole('button',{name:'My Resumes',exact:true}).click();
await page.getByRole('button',{name:'Create a resume',exact:true}).click();
await page.getByLabel('Version label').fill('Browser test revision');
await page.getByLabel('Resume content').fill('TEST USER\nSUMMARY\nConfirmed career details\nSKILLS\nCAD');
await page.getByRole('button',{name:'Save version',exact:true}).click();
await page.getByText('Browser test revision',{exact:true}).waitFor();
await page.getByRole('button',{name:'Create a resume',exact:true}).click();
await page.getByLabel('Resume content').fill('IMMEDIATE CLOSE RECOVERY TEST');
await page.getByRole('button',{name:'Close editor',exact:true}).click();
await page.getByRole('button',{name:'Continue draft',exact:true}).click();
if(await page.getByLabel('Resume content').inputValue()!=='IMMEDIATE CLOSE RECOVERY TEST')throw new Error('Latest draft not recovered');
await page.getByRole('button',{name:'Close editor',exact:true}).click();
await page.getByRole('button',{name:/^Job Matches/}).click();
await page.getByLabel('Search matches').fill('Forma');
const results=await page.locator('.jobs-grid .job-card').count();
if(results!==1)throw new Error('Search expected one result, got '+results);
await page.getByRole('button',{name:'Application Tracker',exact:true}).click();
await page.getByRole('button',{name:'List view',exact:true}).click();
if(await page.locator('.table-row').count()!==4)throw new Error('Tracker rows mismatch');
await page.setViewportSize({width:390,height:844});
await page.goto('http://127.0.0.1:5173/demo',{waitUntil:'networkidle'});
await page.screenshot({path:'outputs/dashboard-mobile.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
if(overflow)throw new Error('Mobile dashboard has horizontal overflow');
await page.getByRole('button',{name:'Open navigation'}).click();
await page.getByRole('button',{name:'My Profile',exact:true}).click();
await page.getByLabel('Full name').fill('Demo Review');
await page.getByRole('button',{name:'Save profile & preferences'}).click();
await page.getByRole('button',{name:'Open navigation'}).click();
await page.getByRole('button',{name:'Alerts',exact:true}).first().click();
if(!await page.getByRole('button',{name:'Save alert preferences',exact:true}).isDisabled())throw new Error('Demo alerts must not send or persist private preferences');
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
await page.screenshot({path:'outputs/home-mobile.png',fullPage:true});
if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth))throw new Error('Mobile home has overflow');
await writeFile('docs/browser-results.json',JSON.stringify({passed:true,viewports:['1440x1100','390x844'],checks:['Home/dashboard rendered','Demo resume saved','Job search filtered','Tracker list viewed','Mobile menu and profile saved','Demo delivery blocked','No horizontal overflow'],pageErrors:errors},null,2));
console.log(JSON.stringify({passed:errors.length===0,pageErrors:errors,checks:7}));
await browser.close();if(errors.length)process.exitCode=1;



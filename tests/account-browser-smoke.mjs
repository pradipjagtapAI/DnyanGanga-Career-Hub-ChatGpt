import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const {chromium}=createRequire(import.meta.url)(process.env.CAREER_PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,channel:process.env.CAREER_BROWSER_CHANNEL||undefined});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const origin='http://127.0.0.1:5173';
await page.goto(origin+'/signin-with-chatgpt?return_to=/dashboard',{waitUntil:'networkidle'});
await page.getByRole('heading',{name:/Good morning/}).waitFor();
const original=await page.evaluate(async()=>fetch('/api/career/state').then(r=>r.json()));
await page.getByRole('button',{name:'My Profile',exact:true}).click();
await page.getByLabel('Full name',{exact:true}).fill('Fictional Browser QA');
const profileResponse=page.waitForResponse(r=>r.url().includes('/api/career/profile')&&r.request().method()==='PUT');
await page.getByRole('button',{name:'Save profile & preferences'}).click();
assert.equal((await profileResponse).status(),200);
await page.getByRole('button',{name:'My Resumes',exact:true}).click();
await page.getByRole('button',{name:'Create a resume',exact:true}).click();
await page.getByLabel('Version label').fill('QA temporary version');
await page.getByLabel('Resume content').fill('FICTIONAL BROWSER TEST\nSUMMARY\nOnly synthetic career content.');
const draftResponse=page.waitForResponse(r=>r.url().includes('/api/career/draft')&&r.request().method()==='PUT');
await page.getByRole('button',{name:'Close editor',exact:true}).click();
assert.equal((await draftResponse).status(),200);
await page.getByRole('button',{name:'Continue draft',exact:true}).click();
assert.equal(await page.getByLabel('Resume content').inputValue(),'FICTIONAL BROWSER TEST\nSUMMARY\nOnly synthetic career content.');
const saveResponse=page.waitForResponse(r=>r.url().endsWith('/api/career/resumes')&&r.request().method()==='POST');
await page.getByRole('button',{name:'Save version',exact:true}).click();
assert.equal((await saveResponse).status(),201);
await page.getByText('QA temporary version',{exact:true}).waitFor();
await page.getByRole('button',{name:'Alerts',exact:true}).first().click();
const noteResponse=page.waitForResponse(r=>r.url().includes('/api/career/notifications')&&r.request().method()==='PUT');
await page.getByRole('button',{name:'Save alert preferences',exact:true}).click();
assert.equal((await noteResponse).status(),200);
await page.reload({waitUntil:'networkidle'});
const now=await page.evaluate(async()=>fetch('/api/career/state').then(r=>r.json()));
assert.equal(now.profile.fullName,'Fictional Browser QA');assert.ok(now.resumes.some(r=>r.title==='QA temporary version'));
const cleanup=await page.evaluate(async({original,ids})=>{const call=async(p,method,body)=>{const r=await fetch('/api/career/'+p,{method,headers:{'Content-Type':'application/json','X-Career-Action':'1'},body:JSON.stringify(body)});if(!r.ok)throw new Error('Cleanup '+r.status);return r.json();};for(const id of ids)await call('resumes/'+id,'DELETE',{});await call('draft','DELETE',{});await call('profile','PUT',{profile:original.profile,preferences:original.preferences});return true;},{original,ids:now.resumes.filter(r=>r.title==='QA temporary version').map(r=>r.id)});
assert.ok(cleanup);assert.deepEqual(errors,[]);console.log(JSON.stringify({passed:true,checks:8,scope:'Real local identity, D1 and browser; synthetic test records cleaned',pageErrors:errors}));
await browser.close();
